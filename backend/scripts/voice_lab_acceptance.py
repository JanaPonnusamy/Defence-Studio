"""Voice Lab end-to-end acceptance with REAL model inference through the real API (spec section 14).

    cd backend
    python scripts/voice_lab_acceptance.py --model parler-tts-mini-v1.1 --language en --workdir <empty dir>

Runs against an isolated DB + storage in --workdir (never the development DB). Steps:
 1. models/system/licences            8. female narrator, plain and with the reference delivery
 2. two narrators (separate identities)   9. timing vs reference (stretch caps, phrase starts, pitch)
 3. reference generated by the model    10. comparison project: 4 tracks, play-ready audio, waveforms
    (male speaker description; no third-party voice)  11. cut / copy / paste / trim / split / join, undo/redo
 4. reference delivery analysis          12. save, restart the application, reopen, verify identical
 5. style profile: label, approve        13. export WAV (normalised) + MP3, integrity check
 6. training preflight (honest hardware gate)  14. Script Studio paragraph contract + reuse
 7. male narrator generation             15. storage report
Writes <workdir>/acceptance_report.json. Exit 0 only if every check passed.
The --language/--model must be supported by the installed model; this script never substitutes one.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
os.environ.setdefault("DEFENCE_STUDIO_VOICE_LAB_WORKER", "0")

SECRET = "voice-lab-acceptance-secret-0123456789abcdef"
os.environ.setdefault("DEFENCE_STUDIO_AUTH_SECRET", SECRET)

from fastapi.testclient import TestClient  # noqa: E402

from defence_studio.api.app import create_app  # noqa: E402

TEXTS = {
    "en": "The squadron took off before dawn. Radar picked up the formation over the sea. "
          "Within minutes, the interceptors were airborne. The mission ended without a shot being fired.",
    "ta": "விமானப் படை விடியற்காலையில் புறப்பட்டது. கடலின் மேல் ரேடார் அவற்றைக் கண்டது. "
          "சில நிமிடங்களில் இடைமறிப்பு விமானங்கள் வானில் இருந்தன. ஒரு குண்டு கூட சுடப்படாமல் பணி முடிந்தது.",
}
SPEAKERS = {"male": ("Jon", "Jon's voice is deep and authoritative, delivering a dramatic news briefing with "
                     "emphatic pauses. The recording is very clear with no background noise."),
            "female": ("Laura", "Laura's voice is clear and expressive, speaking at a moderate pace. "
                       "The recording is very clear with no background noise.")}


def token():
    import base64, hashlib, hmac
    enc = lambda v: base64.urlsafe_b64encode(v).rstrip(b"=").decode()
    h = enc(json.dumps({"alg": "HS256", "typ": "JWT"}).encode())
    p = enc(json.dumps({"sub": "acceptance-owner", "exp": int(time.time()) + 86400}).encode())
    s = enc(hmac.new(os.environ["DEFENCE_STUDIO_AUTH_SECRET"].encode(), f"{h}.{p}".encode(), hashlib.sha256).digest())
    return f"{h}.{p}.{s}"


class Run:
    def __init__(self, path):
        self.checks, self.data, self.path = [], {}, path

    def check(self, name, cond, **ev):
        self.checks.append({"check": name, "pass": bool(cond), **ev})
        print(("PASS " if cond else "FAIL ") + name + (f"  {json.dumps(ev, default=str)[:240]}" if ev else ""), flush=True)
        return cond

    def save(self):
        out = {"schema": "defence-studio.voice-lab-acceptance.v1", "finished_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
               "passed": sum(c["pass"] for c in self.checks), "failed": sum(not c["pass"] for c in self.checks),
               "checks": self.checks, "data": self.data}
        self.path.write_text(json.dumps(out, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
        return out


def ok(r, code=None):
    if code is not None and r.status_code != code:
        raise RuntimeError(f"HTTP {r.status_code} (want {code}): {r.text[:600]}")
    return r.json()


def wait(svc, c, H, url, key="status", done=("COMPLETED", "ANALYSED", "FAILED", "CANCELLED")):
    t = time.perf_counter()
    while True:
        svc.run_pending(limit=1)
        d = ok(c.get(url, headers=H), 200)
        if d.get(key) in done:
            return d, round(time.perf_counter() - t, 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--language", required=True)
    ap.add_argument("--workdir", required=True)
    a = ap.parse_args()
    wd = Path(a.workdir)
    wd.mkdir(parents=True, exist_ok=True)
    if any(wd.iterdir()):
        sys.exit("--workdir must be empty")
    os.environ.setdefault("DEFENCE_STUDIO_VOICE_LAB_RESERVE_BYTES", str(1024 ** 3))
    db, store = wd / "acceptance.sqlite3", wd / "storage"
    R = Run(wd / "acceptance_report.json")
    H = {"Authorization": f"Bearer {token()}"}
    text = TEXTS[a.language]

    app = create_app(db, os.environ["DEFENCE_STUDIO_AUTH_SECRET"], store)
    with TestClient(app) as c:
        svc = app.state.voice_lab
        models = {m["model_id"]: m for m in ok(c.get("/api/voice-lab/models", headers=H), 200)["models"]}
        m = models[a.model]
        R.data["model"] = {k: m[k] for k in ("model_id", "commit", "weights_rev", "code_licence", "weight_licence",
                                             "data_licence", "commercial", "production_allowed")}
        if not R.check("1. requested model installed at pinned revision", m["install"]["installed"], install=m["install"]):
            return R.save()
        R.check("1b. language supported by the model", a.language in m["languages"], languages=m["languages"])
        sysinfo = ok(c.get("/api/voice-lab/system", headers=H), 200)
        R.data["hardware"] = {k: sysinfo.get(k) for k in ("cpu", "ram_bytes", "gpus", "cuda_usable", "training_blockers")}

        # 2. narrators
        ids = {}
        for gender in ("male", "female"):
            con = ok(c.post("/api/voice-lab/consents", headers=H, json={
                "subject_name": f"{gender} evaluation narrator (model base speaker)", "subject_role": "NARRATOR",
                "scope": ["GENERATION"], "document_ref": "evaluation: base-model speaker, no human voice used"}), 201)
            n = ok(c.post("/api/voice-lab/narrators", headers=H, json={
                "display_name": f"Evaluation {gender} narrator", "gender_label": gender, "languages": [a.language],
                "consent_id": con["consent_id"]}), 201)
            spk, desc = SPEAKERS[gender]
            v = ok(c.post(f"/api/voice-lab/narrators/{n['narrator_id']}/versions", headers=H, json={
                "model_id": a.model, "speaker": spk, "description": desc}), 201)
            ids[gender] = (n["narrator_id"], v["model_version_id"])
        r = c.post(f"/api/voice-lab/narrators/{ids['female'][0]}/versions", headers=H,
                   json={"model_id": a.model, "speaker": "jon", "description": "x"})
        R.check("2. a voice identity cannot be attached to a second narrator", r.status_code == 409)

        # 3. reference: male speaker generated by the model (dramatic delivery)
        gref = ok(c.post("/api/voice-lab/generations", headers=H, json={
            "narrator_id": ids["male"][0], "text": text, "language": a.language, "config": {"seed": 7}}), 202)
        gref, secs = wait(svc, c, H, f"/api/voice-lab/generations/{gref['generation_id']}")
        R.check("3. reference speech generated by real model", gref["status"] == "COMPLETED",
                seconds=secs, error=gref.get("error"), runtime=(gref.get("provenance") or {}).get("runtime"))
        if gref["status"] != "COMPLETED":
            return R.save()
        R.data["reference_generation"] = {"generation_id": gref["generation_id"], "duration_ms": gref["audio"]["duration_ms"],
                                          "runtime": gref["provenance"]["runtime"]}
        ref_wav = c.get(gref["audio"]["url"], headers=H).content
        ref = ok(c.post("/api/voice-lab/references", headers=H, files={"file": ("reference.wav", ref_wav, "audio/wav")},
                        data={"name": "Male reference (model-generated)",
                              "authorization_ref": "generated by the evaluation model in this run"}), 202)
        ref, _ = wait(svc, c, H, f"/api/voice-lab/references/{ref['reference_id']}")
        an = ok(c.get(f"/api/voice-lab/references/{ref['reference_id']}/prosody", headers=H), 200)
        s = an["summary"]
        R.check("4. reference delivery analysed (pitch, pauses, rate, energy)", ref["status"] == "ANALYSED" and s["phrase_count"] >= 2,
                f0_median_hz=s["f0_median_hz"], f0_range=[s["f0_min_hz"], s["f0_max_hz"]], phrases=s["phrase_count"],
                pause_mean_ms=s["pause_mean_ms"], rate=s["rate_syl_per_s_estimate"], emotion=s["emotion"])
        R.data["reference_analysis"] = {"summary": s, "phrases": [{k: p[k] for k in ("t0_ms", "t1_ms", "pause_after_ms",
                                                                                     "rel_median_st", "intonation")}
                                                                  for p in an["phrases"]]}
        st = ok(c.post("/api/voice-lab/style-profiles", headers=H,
                       json={"reference_id": ref["reference_id"], "name": "Dramatic briefing"}), 201)
        ok(c.patch(f"/api/voice-lab/style-profiles/{st['style_profile_id']}/labels", headers=H,
                   json={"feature_key": "delivery_label", "value": {"label": "DRAMATIC_BRIEFING", "notes": "acceptance run"}}), 200)
        st = ok(c.post(f"/api/voice-lab/style-profiles/{st['style_profile_id']}/approve", headers=H), 200)
        R.check("5. style profile saved and approved", st["status"] == "APPROVED")

        # 6. training gate on this hardware
        pf = ok(c.get("/api/voice-lab/system", headers=H), 200)
        R.check("6. training capability reported from measured hardware", "training_supported" in pf,
                training_supported=pf["training_supported"], blockers=pf["training_blockers"])

        # 7/8. narrators
        gens = {}
        for label, body in {
            "male_narrator": {"narrator_id": ids["male"][0], "config": {"seed": 21}},
            "female_narrator": {"narrator_id": ids["female"][0], "config": {"seed": 21}},
            "female_styled": {"narrator_id": ids["female"][0], "config": {"seed": 21},
                              "style_profile_id": st["style_profile_id"]},
        }.items():
            g = ok(c.post("/api/voice-lab/generations", headers=H, json={"text": text, "language": a.language, **body}), 202)
            g, secs = wait(svc, c, H, f"/api/voice-lab/generations/{g['generation_id']}")
            gens[label] = g
            R.check(f"7. {label} generated", g["status"] == "COMPLETED", seconds=secs, error=g.get("error"),
                    duration_ms=(g.get("audio") or {}).get("duration_ms"))
        fs, fp = gens["female_styled"], gens["female_narrator"]
        if fs["status"] == "COMPLETED":
            rep = fs["timing"]["style_report"]
            cmpd = rep.get("comparison") or {}
            R.data["style_transfer"] = {"mode": rep["mode"], "reference_ms": rep.get("reference_duration_ms"),
                                        "raw_ms": rep["raw_duration_ms"], "output_ms": rep["output_duration_ms"],
                                        "duration_diff_ms": rep.get("duration_diff_ms"),
                                        "stretch_capped_phrases": rep.get("stretch_capped_phrases"),
                                        "pitch_clamped_phrases": rep.get("pitch_clamped_phrases"),
                                        "phrases": rep.get("phrases"), "comparison": cmpd,
                                        "reason": rep.get("reason")}
            R.check("8. reference delivery applied to the female narrator", rep["mode"] in ("PHRASE_MAPPED", "GLOBAL_FALLBACK"),
                    mode=rep["mode"], reason=rep.get("reason"))
            fem_plain = ok(c.get(f"/api/voice-lab/artifacts/{fp['artifact_id']}/analysis", headers=H), 200)["prosody"]["summary"]
            fem_sty = ok(c.get(f"/api/voice-lab/artifacts/{fs['artifact_id']}/analysis", headers=H), 200)["prosody"]["summary"]
            R.data["pitch_identity"] = {"reference_f0_median_hz": s["f0_median_hz"],
                                        "female_plain_f0_median_hz": fem_plain["f0_median_hz"] if fem_plain else None,
                                        "female_styled_f0_median_hz": fem_sty["f0_median_hz"] if fem_sty else None}
            if fem_plain and fem_sty:
                drift = abs(12 * __import__("math").log2(fem_sty["f0_median_hz"] / fem_plain["f0_median_hz"]))
                R.check("9. female pitch centre kept (not copied from the male reference)", drift <= 2.0,
                        styled_vs_plain_semitones=round(drift, 2), **R.data["pitch_identity"])
            R.check("9b. timing deviation measured and reported", rep.get("output_duration_ms") is not None,
                    target_ms=rep.get("target_duration_ms"), output_ms=rep.get("output_duration_ms"),
                    diff_ms=rep.get("duration_diff_ms"), phrase_start_error_ms=cmpd.get("phrase_start_error_ms"))

        # 10. comparison project
        p = ok(c.post("/api/voice-lab/projects", headers=H, json={"name": "Acceptance comparison"}), 201)
        pid = p["project_id"]
        doc = ok(c.post(f"/api/voice-lab/projects/{pid}/comparison", headers=H, json={"tracks": [
            {"role": "male_reference", "name": "Male reference", "reference_id": ref["reference_id"]},
            {"role": "male_narrator", "name": "Male narrator", "generation_id": gens["male_narrator"]["generation_id"]},
            {"role": "female_narrator", "name": "Female narrator", "generation_id": fp["generation_id"]},
            {"role": "female_styled", "name": "Female + reference delivery", "generation_id": fs["generation_id"]}]}), 200)
        R.check("10. four comparison tracks loaded", len(doc["tracks"]) == 4, duration_ms=doc["duration_ms"])
        for t in doc["tracks"]:
            aid = t["clips"][0]["artifact_id"]
            au = c.get(f"/api/voice-lab/artifacts/{aid}/audio", headers={**H, "Range": "bytes=0-1023"})
            wf = ok(c.get(f"/api/voice-lab/artifacts/{aid}/waveform?px_per_s=50", headers=H), 200)
            R.check(f"10b. {t['role']} playable (range request) + waveform", au.status_code in (200, 206) and len(wf["max"]) > 10,
                    http=au.status_code, buckets=len(wf["max"]))
        cmpr = ok(c.get("/api/voice-lab/compare?artifact_ids=" + ",".join(t["clips"][0]["artifact_id"] for t in doc["tracks"]),
                        headers=H), 200)
        R.data["comparison"] = [{k: i.get(k) for k in ("artifact_id", "duration_ms", "phrase_starts_ms", "pauses_ms",
                                                       "relative_pitch_st", "vs_first")} for i in cmpr["items"]]

        # 11. edits on the female narrator track
        tid = next(t["track_id"] for t in doc["tracks"] if t["role"] == "female_narrator")
        clip = next(t for t in doc["tracks"] if t["role"] == "female_narrator")["clips"][0]
        op = lambda o: ok(c.post(f"/api/voice-lab/projects/{pid}/ops", headers=H, json={"op": o}), 200)
        L = clip["out_ms"]
        cut = op({"type": "cut_range", "track_id": tid, "t0_ms": L // 4, "t1_ms": L // 4 + 500, "ripple": True})
        board = cut["result"]["clipboard"]
        copied = ok(c.post(f"/api/voice-lab/projects/{pid}/ops", headers=H, json={"op": {
            "type": "copy_range", "track_id": tid, "t0_ms": 0, "t1_ms": 400}}), 200)["result"]["clipboard"]
        op({"type": "paste", "track_id": tid, "at_ms": L, "clipboard": board})
        d = op({"type": "paste", "track_id": tid, "at_ms": L + 1000, "clipboard": copied})["doc"]
        clips = next(t for t in d["tracks"] if t["track_id"] == tid)["clips"]
        op({"type": "update_clip", "clip_id": clips[0]["clip_id"], "in_ms": 50})  # trim
        sp = op({"type": "split_clip", "clip_id": clips[-1]["clip_id"], "at_ms": clips[-1]["start_ms"] + 200})["result"]
        j = op({"type": "join_clips", "clip_ids": [sp["left_clip_id"], sp["right_clip_id"]]})
        u = ok(c.post(f"/api/voice-lab/projects/{pid}/undo", headers=H), 200)
        rr = ok(c.post(f"/api/voice-lab/projects/{pid}/redo", headers=H), 200)
        R.check("11. cut, copy, paste, trim, split, join, undo, redo", j["result"]["mode"] == "MERGED_WINDOWS"
                and rr["doc"]["revision"] == u["doc"]["revision"] + 1, revision=rr["doc"]["revision"])
        saved = ok(c.get(f"/api/voice-lab/projects/{pid}", headers=H), 200)

    # 12. restart
    app2 = create_app(db, os.environ["DEFENCE_STUDIO_AUTH_SECRET"], store)
    with TestClient(app2) as c2:
        svc2 = app2.state.voice_lab
        again = ok(c2.get(f"/api/voice-lab/projects/{pid}", headers=H), 200)
        R.check("12. project identical after application restart", again["tracks"] == saved["tracks"]
                and again["revision"] == saved["revision"], revision=again["revision"])
        # 13. export
        ex = ok(c2.post(f"/api/voice-lab/projects/{pid}/export", headers=H,
                        json={"format": "wav", "normalize_lufs": -16, "channels": 2}), 201)
        R.check("13. WAV export integrity", ex["integrity"]["duration_match"], **ex["integrity"],
                lufs_after=ex["loudness_after"]["integrated_lufs"], peak_limited=ex["peak_limited"])
        mp3 = ok(c2.post(f"/api/voice-lab/projects/{pid}/export", headers=H, json={"format": "mp3"}), 201)
        R.check("13b. MP3 export integrity", mp3["integrity"]["duration_match"], **mp3["integrity"])
        ok(c2.post(f"/api/voice-lab/artifacts/{ex['artifact']['artifact_id']}/approve", headers=H), 200)
        R.data["exports"] = {"wav": ex["artifact"]["rel_path"], "mp3": mp3["artifact"]["rel_path"]}
        # 14. Script Studio
        sres = ok(c2.post("/api/voice-lab/script-generation", headers=H, json={
            "text": text, "narrator_id": ids["female"][0], "style_profile_id": st["style_profile_id"], "language": a.language,
            "config": {"seed": 21}, "script_id": "acceptance", "chapter_id": "ch1", "paragraph_id": "p1"}), 202)
        R.check("14. Script Studio paragraph reuses unchanged audio", sres["reused"] and sres["status"] == "COMPLETED",
                generation_id=sres["generation_id"], limitations=sres["limitations"])
        R.check("14b. returned provenance includes model + narrator version", bool(sres["provenance"]["weights_revision"])
                and sres["narrator"]["model_version"] == 1)
        rv = ok(c2.post("/api/voice-lab/reviews", headers=H, json={"artifact_id": fs["artifact_id"],
                                                                   "generation_id": fs["generation_id"],
                                                                   "ratings": {}, "notes": "automated run: no listening "
                                                                   "evaluation performed"}), 201)
        R.check("14c. review stored against model version", rv["model_version_id"] == ids["female"][1])
        # 15. storage
        storage = ok(c2.get("/api/voice-lab/storage", headers=H), 200)
        R.check("15. storage report: all registered files present, all preserved", not storage["missing_files"],
                registered_bytes=storage["registered_bytes"], by_kind={k: v["count"] for k, v in storage["by_kind"].items()})
        svc2.shutdown()
    out = R.save()
    print(json.dumps({"passed": out["passed"], "failed": out["failed"], "report": str(R.path)}))
    sys.exit(0 if out["failed"] == 0 else 1)


if __name__ == "__main__":
    main()
