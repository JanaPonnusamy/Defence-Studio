"""Deterministic epistemic-integrity checks and script comparison (RM-2).

Pure functions over an approved evidence package and a script revision body.
Nothing here asks a model to judge itself. The statement-kind vocabulary is:

* ``VERIFIED_FACT``   -- asserted as fact. Requires every cited claim to be
  corroborated by >= 2 *independent* sources (sources in one duplicate group
  count once) and to carry no unresolved conflict.
* ``ATTRIBUTED_CLAIM``-- "X says ...". Needs approved evidence, no corroboration.
* ``ANALYSIS``        -- the writer's interpretation; must be qualified.
* ``UNRESOLVED``      -- an open question or contradicted/uncorroborated point,
  presented as such; must be qualified.

Being generated by a model never makes anything a VERIFIED_FACT; only
corroborated, human-approved evidence can support that label.
"""
from __future__ import annotations

import re
import unicodedata
from datetime import date

from defence_studio.discovery.ranking import parse_date

INTEGRITY_VERSION = "defence-studio.script-integrity.v1"
STATEMENT_KINDS = ("VERIFIED_FACT", "ATTRIBUTED_CLAIM", "ANALYSIS", "UNRESOLVED")
STALE_AFTER_DAYS = 180

_NUM_RE = re.compile(r"\d[\d,]*(?:\.\d+)?")


def _norm_number(token: str) -> str:
    return token.replace(",", "").rstrip(".")


def numbers_in(text: str) -> list[str]:
    out = []
    for m in _NUM_RE.finditer(unicodedata.normalize("NFKC", text or "")):
        out.append(_norm_number(m.group(0)))
    return out


def independent_source_clusters(package: dict) -> dict[str, str]:
    """source_id -> cluster id. Sources in the same duplicate group share one
    cluster, so syndicated copies are never counted as corroboration."""
    cluster = {s["source_id"]: s["source_id"] for s in package.get("sources", [])}
    for group in package.get("duplicate_groups", []):
        members = [m for m in group.get("member_source_ids", []) if m in cluster]
        if members:
            rep = group.get("representative_source_id") or members[0]
            for m in members:
                cluster[m] = f"dup:{rep}"
    return cluster


def corroboration_count(package: dict, claim_id: str) -> int:
    """Independent source clusters that state the same assertion as claim_id.
    Uses claim_groups (textual relationship) only as a *candidate* for
    corroboration; independence comes from the duplicate clustering."""
    claims = {c["claim_id"]: c for c in package.get("claims", [])}
    if claim_id not in claims:
        return 0
    cluster = independent_source_clusters(package)
    members = {claim_id}
    for group in package.get("claim_groups", []):
        if claim_id in group.get("member_claim_ids", []):
            members.update(group.get("member_claim_ids", []))
    return len({cluster.get(claims[m]["source_id"], claims[m]["source_id"]) for m in members if m in claims})


def conflicted_claim_ids(package: dict) -> set[str]:
    out = set()
    for conflict in package.get("conflicts", []):
        out.update(c for c in (conflict.get("claim_id_a"), conflict.get("claim_id_b")) if c)
    return out


def _reference_date(package: dict) -> date | None:
    ts = package.get("generated_from_timestamp")
    return parse_date(ts) if isinstance(ts, str) else None


def integrity_issues(revision: dict, package: dict) -> list[dict]:
    """Issues to merge into the validator output. Never touches the model."""
    issues: list[dict] = []
    claims = {c["claim_id"]: c for c in package.get("claims", [])}
    sources = {s["source_id"]: s for s in package.get("sources", [])}
    conflicted = conflicted_claim_ids(package)
    ref = _reference_date(package)

    def add(code, severity, sid, detail):
        issues.append(dict(code=code, severity=severity, section_id=sid, detail=detail))

    target = (revision.get("config") or {}).get("target_words")
    for section in revision.get("sections", []):
        sid = section.get("section_id", "")
        evidence = section.get("evidence") or {}
        cited = [c for c in evidence.get("claim_ids", []) if c in claims]
        kind = section.get("statement_kind")
        factual = section.get("requires_evidence", True)
        if kind is not None and kind not in STATEMENT_KINDS:
            add("UNKNOWN_STATEMENT_KIND", "ERROR", sid, f"statement_kind {kind!r} is not recognised")
            continue
        if factual and kind is None:
            add("STATEMENT_KIND_MISSING", "WARNING", sid,
                "No statement_kind; the epistemic status of this section is undeclared")
        qualification = (evidence.get("qualification") or "").strip()
        if kind in ("ANALYSIS", "UNRESOLVED") and not qualification:
            add("UNQUALIFIED_" + kind, "ERROR", sid, f"A {kind} section must carry a qualification note")
        if kind == "VERIFIED_FACT":
            weak = [c for c in cited if corroboration_count(package, c) < 2]
            if not cited or weak:
                add("FACT_NOT_CORROBORATED", "ERROR", sid,
                    f"Presented as VERIFIED_FACT but not corroborated by >=2 independent sources: {weak or 'no claims cited'}")
        hit = [c for c in cited if c in conflicted]
        if hit:
            if kind in ("VERIFIED_FACT", None):
                add("CONTRADICTED_CLAIM_AS_FACT", "ERROR" if kind else "WARNING", sid,
                    f"Cites claim(s) involved in a source conflict without framing them as attributed/unresolved: {hit}")
        # Numbers must come from the cited evidence (deterministic, no model).
        if factual and cited:
            support = " ".join(claims[c].get("claim_text", "") for c in cited)
            allowed = set(numbers_in(support))
            missing = sorted({n for n in numbers_in(section.get("narration", "")) if n not in allowed})
            if missing:
                add("UNSUPPORTED_NUMBER", "ERROR", sid,
                    f"Numeric value(s) not present in the cited evidence: {missing}")
        # Stale / undated sources.
        for c in cited:
            src = sources.get(claims[c].get("source_id"), {})
            published = (src.get("declared_metadata") or {}).get("published_at") or claims[c].get("source_published_at")
            parsed = parse_date(published) if isinstance(published, str) and published else None
            if parsed is None:
                add("SOURCE_DATE_UNKNOWN", "WARNING", sid, f"Claim {c}: source publication date is unavailable")
            elif ref is not None and (ref - parsed).days > STALE_AFTER_DAYS:
                add("STALE_SOURCE", "WARNING", sid,
                    f"Claim {c}: source was published {(ref - parsed).days} days before the evidence snapshot")
    # Length target (warning only; the target is configuration, not a fact).
    words = (revision.get("word_count") or {}).get("words")
    if isinstance(target, int) and target > 0 and isinstance(words, int) and abs(words - target) / target > 0.25:
        issues.append(dict(code="TARGET_LENGTH_MISSED", severity="WARNING", section_id="",
                           detail=f"{words} words versus a target of {target} (outside +/-25%)"))
    return issues


