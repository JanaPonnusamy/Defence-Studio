def _spoken(revision: dict) -> str:
    parts = [revision.get("opening_hook", "")]
    parts += [s.get("narration", "") for s in revision.get("sections", [])]
    parts.append(revision.get("closing", ""))
    return " ".join(p for p in parts if p)


def shingles(text: str, n: int = 5) -> set[tuple[str, ...]]:
    words = re.findall(r"\w+", unicodedata.normalize("NFKC", text).lower(), flags=re.UNICODE)
    if len(words) < n:
        return {tuple(words)} if words else set()
    return {tuple(words[i:i + n]) for i in range(len(words) - n + 1)}


def overlap_ratio(a: str, b: str) -> float:
    """Share of the *smaller* script's 5-word phrases that also occur in the other."""
    sa, sb = shingles(a), shingles(b)
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / min(len(sa), len(sb))


def compare_revisions(old: dict, new: dict) -> dict:
    old_sections = {s["section_id"]: s for s in old.get("sections", [])}
    new_sections = {s["section_id"]: s for s in new.get("sections", [])}
    changed = [sid for sid in new_sections if sid in old_sections
               and new_sections[sid].get("narration") != old_sections[sid].get("narration")]
    old_claims = {c for s in old.get("sections", []) for c in (s.get("evidence") or {}).get("claim_ids", [])}
    new_claims = {c for s in new.get("sections", []) for c in (s.get("evidence") or {}).get("claim_ids", [])}
    return {
        "old_version": old.get("version"), "new_version": new.get("version"),
        "overlap_ratio": round(overlap_ratio(_spoken(old), _spoken(new)), 4),
        "title_changed": old.get("title") != new.get("title"),
        "sections_added": sorted(set(new_sections) - set(old_sections)),
        "sections_removed": sorted(set(old_sections) - set(new_sections)),
        "sections_changed": sorted(changed),
        "claims_added": sorted(new_claims - old_claims),
        "claims_removed": sorted(old_claims - new_claims),
        "package_changed": old.get("package_sha256") != new.get("package_sha256"),
        "word_delta": (new.get("word_count") or {}).get("words", 0) - (old.get("word_count") or {}).get("words", 0),
    }


REPEAT_THRESHOLD = 0.35


def repetition_against(candidate: dict, others: list[dict]) -> list[dict]:
    """Prior scripts (other jobs / versions) sharing >= REPEAT_THRESHOLD of
    their 5-word phrases with ``candidate``. Each ``others`` item carries
    ``job_id``, ``version`` and ``body``."""
    text = _spoken(candidate)
    found = []
    for other in others:
        ratio = overlap_ratio(text, _spoken(other["body"]))
        if ratio >= REPEAT_THRESHOLD:
            found.append({"job_id": other["job_id"], "version": other["version"],
                          "topic": other.get("topic"), "overlap_ratio": round(ratio, 4),
                          "flag": "REPEATED_WORDING"})
    return sorted(found, key=lambda f: -f["overlap_ratio"])
